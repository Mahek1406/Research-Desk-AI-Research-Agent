"""
Data validation schemas for ResearchDesk.
Defines models for research requests, plans, tool outputs, citations, and syntheses.
"""

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field, HttpUrl


class ConfidenceLevel(str, Enum):
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"


class RetrievalStatus(str, Enum):
    SUCCESS = "success"
    PARTIAL = "partial"
    FAILED = "failed"
    SKIPPED = "skipped"


class ResearchRequest(BaseModel):
    """Input payload for research queries."""
    question: str = Field(
        ...,
        min_length=5,
        max_length=1000,
        description="The research question to investigate",
        examples=["Compare the top three open-source vector databases for a startup building RAG products."]
    )
    max_sources: int = Field(
        default=5,
        ge=1,
        le=10,
        description="Maximum number of research sources to incorporate"
    )
    include_web_scraping: bool = Field(
        default=True,
        description="Whether to retrieve and parse full webpage text beyond search snippets"
    )


class PlanStep(BaseModel):
    """A distinct step inside an agent's research plan."""
    step_number: int = Field(..., ge=1)
    title: str = Field(..., min_length=2)
    description: str = Field(...)
    tool_to_use: Optional[str] = Field(default=None)
    status: str = Field(default="pending", description="pending, in_progress, completed, failed, skipped")


class ResearchPlan(BaseModel):
    """Structured plan generated by the Question Analyzer and Planner."""
    objective: str
    subquestions: List[str] = Field(default_factory=list)
    steps: List[PlanStep] = Field(default_factory=list)
    initial_assumptions: List[str] = Field(default_factory=list)


class SourceItem(BaseModel):
    """A validated information source collected during research."""
    id: str = Field(..., description="Unique source token like [S1], [S2]")
    title: str = Field(..., description="Webpage or article title")
    url: str = Field(..., description="Absolute source URL")
    domain: str = Field(..., description="Extracted hostname/domain")
    snippet: str = Field(..., description="Search snippet or short excerpt")
    extracted_text: Optional[str] = Field(default=None, description="Cleaned article body text")
    retrieval_status: RetrievalStatus = Field(default=RetrievalStatus.SUCCESS)
    relevance_note: Optional[str] = Field(default=None)


class KeyFinding(BaseModel):
    """A verified, source-grounded key finding."""
    claim: str = Field(..., description="Concise statement of fact or comparison")
    detail: str = Field(..., description="Detailed elaboration or evidence")
    supporting_source_ids: List[str] = Field(
        default_factory=list,
        description="Source IDs that support this finding, e.g. ['[S1]', '[S3]']"
    )


class ExecutionTraceStep(BaseModel):
    """Operational audit log entry for the agent's execution timeline."""
    stage: str
    status: str = "completed"
    message: str
    timestamp: str
    duration_ms: Optional[float] = None


class ResearchResponse(BaseModel):
    """Complete, structured output of the AI Research Agent."""
    question: str
    short_answer: str = Field(
        ...,
        description="A direct 2-4 sentence executive summary answering the question"
    )
    detailed_analysis: str = Field(
        ...,
        description="In-depth analysis organized by themes or comparisons in GitHub Markdown"
    )
    key_findings: List[KeyFinding] = Field(
        default_factory=list,
        description="Structured key findings backed by source identifiers"
    )
    sources_used: List[SourceItem] = Field(
        default_factory=list,
        description="All sources retrieved and cited during the research workflow"
    )
    confidence_level: ConfidenceLevel = Field(
        ...,
        description="Confidence scale reflecting evidence quantity, source relevance, and consistency"
    )
    confidence_explanation: str = Field(
        ...,
        description="Transparent justification of why this confidence level was assigned"
    )
    assumptions: List[str] = Field(
        default_factory=list,
        description="Assumptions made due to scope or missing context"
    )
    limitations: List[str] = Field(
        default_factory=list,
        description="Data limitations, date cutoffs, or inaccessible sources"
    )
    suggested_next_steps: List[str] = Field(
        default_factory=list,
        description="Practical follow-up investigations or implementation recommendations"
    )
    research_plan: ResearchPlan
    execution_trace: List[ExecutionTraceStep] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)


class HealthResponse(BaseModel):
    """Service status and readiness response."""
    status: str
    version: str
    llm_configured: bool
    llm_provider: str
    llm_model: str
    search_provider: str
